import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root = new URL('../../',import.meta.url);
const inputs=['jd-cookie-local/src/core.mjs','jd-cookie-local/src/runner.mjs','jd-cookie-local/src/adapter.js'];
const chunks=[],files=[];
for(const file of inputs){
  const bytes=await fs.readFile(new URL(file,root));files.push({path:file,sha256:createHash('sha256').update(bytes).digest('hex')});
  chunks.push(bytes.toString('utf8').replace(/^export (async )?function /gm,(_,asyncWord)=>(asyncWord||'')+'function '));
}
const output='/* 京东网页 Cookie 捕获 / Loon 手动登录校验。\n * EXPERIMENTAL: real-device compatibility and bean query verification pending.\n * See jd-cookie-local/README.md and NOTICE.md. Generated by tools/build.mjs.\n * No wskey conversion, signing, uploads or automatic refresh.\n */\n(function () {\n\'use strict\';\n'+chunks.join('\n')+'\n})();\n';
const path=new URL('get_jd_wskey.js',root);
if(process.argv.includes('--check')){
  if(await fs.readFile(path,'utf8')!==output)throw Error('Bundle is stale');
}else{
  await fs.writeFile(path,output);
  await fs.writeFile(new URL('jd-cookie-local/source-manifest.json',root),JSON.stringify({files,bundleSha256:createHash('sha256').update(output).digest('hex')},null,2)+'\n');
}
console.log(JSON.stringify({bundle:'get_jd_wskey.js',sha256:createHash('sha256').update(output).digest('hex')}));
